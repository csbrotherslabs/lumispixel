from django.core.management.base import BaseCommand

from apps.visual_search.vector_store import vector_connection


class Command(BaseCommand):
    help = "Create the isolated application face-vector table in the configured PostgreSQL database."

    def handle(self, *args, **options):
        with vector_connection() as conn:
            with conn.transaction():
                conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
                conn.execute("CREATE SCHEMA IF NOT EXISTS visual_search")
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS visual_search.app_face_embeddings (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        photo_id bigint NOT NULL,
                        gallery_id bigint NOT NULL,
                        photographer_id bigint NOT NULL,
                        source_version integer NOT NULL,
                        model_version varchar(80) NOT NULL,
                        face_index integer NOT NULL,
                        embedding vector(512) NOT NULL,
                        created_at timestamptz NOT NULL DEFAULT now(),
                        UNIQUE (photo_id, source_version, model_version, face_index)
                    )
                """)
                conn.execute("""
                    CREATE INDEX IF NOT EXISTS app_face_embeddings_photo_idx
                    ON visual_search.app_face_embeddings (photo_id)
                """)
        self.stdout.write(self.style.SUCCESS("Face vector store schema ready."))
