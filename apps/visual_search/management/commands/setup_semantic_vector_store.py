from django.core.management.base import BaseCommand
from apps.visual_search.vector_store import vector_connection

class Command(BaseCommand):
    help="Create isolated semantic vectors; never share biometric vector tables."
    def handle(self,*args,**options):
        with vector_connection() as conn:
            with conn.transaction():
                conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
                conn.execute("CREATE SCHEMA IF NOT EXISTS visual_search")
                conn.execute("""CREATE TABLE IF NOT EXISTS visual_search.app_semantic_embeddings (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    photo_id bigint NOT NULL UNIQUE,
                    gallery_id bigint NOT NULL,
                    model_version varchar(80) NOT NULL,
                    embedding vector(512) NOT NULL,
                    created_at timestamptz NOT NULL DEFAULT now()
                )""")
                conn.execute("CREATE INDEX IF NOT EXISTS app_semantic_gallery_idx ON visual_search.app_semantic_embeddings (gallery_id)")
        self.stdout.write(self.style.SUCCESS("Independent semantic vector store ready."))
