"""Isolated integration tests for the face-vector persistence and lifecycle.

Set VISUAL_SEARCH_INTEGRATION_DATABASE_URL to a disposable PostgreSQL database.
Never point these tests at a production or research database.
"""
import os
import unittest
from unittest.mock import patch
from uuid import uuid4

from django.test import SimpleTestCase, TestCase, override_settings


@unittest.skipUnless(
    os.environ.get("VISUAL_SEARCH_INTEGRATION_DATABASE_URL"),
    "Requires VISUAL_SEARCH_INTEGRATION_DATABASE_URL for a disposable test database",
)
class VectorStoreIntegrationTests(SimpleTestCase):
    """Real pgvector operations, with isolated IDs and guaranteed cleanup."""

    databases = set()

    def setUp(self):
        self.url = os.environ["VISUAL_SEARCH_INTEGRATION_DATABASE_URL"]
        self.photo_id = uuid4().int % (2**61)
        self.gallery_id = uuid4().int % (2**61)
        self.photographer_id = uuid4().int % (2**61)
        from apps.visual_search.vector_store import vector_connection
        with override_settings(VISUAL_SEARCH_DATABASE_URL=self.url):
            with vector_connection() as conn:
                name = conn.execute("SELECT current_database()").fetchone()[0]
                if name in {"defaultdb", "lumispixel_visual_search"}:
                    self.fail("Refusing to run destructive integration tests on shared database " + name)
                if not name.startswith("lumispixel_visual_search_test"):
                    self.fail("Integration database name must start with lumispixel_visual_search_test")
                conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
                conn.execute("CREATE SCHEMA IF NOT EXISTS visual_search")
                conn.execute("""CREATE TABLE IF NOT EXISTS visual_search.app_face_embeddings (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    photo_id bigint NOT NULL,
                    gallery_id bigint NOT NULL,
                    photographer_id bigint NOT NULL,
                    source_version integer NOT NULL,
                    model_version varchar(80) NOT NULL,
                    face_index integer NOT NULL,
                    embedding vector(512) NOT NULL,
                    created_at timestamptz NOT NULL DEFAULT now(),
                    UNIQUE (photo_id, source_version, model_version, face_index)
                )""")

    def tearDown(self):
        from apps.visual_search.vector_store import delete_photo_embeddings
        with override_settings(VISUAL_SEARCH_DATABASE_URL=self.url):
            delete_photo_embeddings(self.photo_id)

    def _count(self):
        from apps.visual_search.vector_store import vector_connection
        with override_settings(VISUAL_SEARCH_DATABASE_URL=self.url):
            with vector_connection() as conn:
                return conn.execute(
                    "SELECT count(*) FROM visual_search.app_face_embeddings WHERE photo_id = %s",
                    (self.photo_id,),
                ).fetchone()[0]

    def test_replace_is_idempotent_and_photo_purge(self):
        import numpy as np
        from apps.visual_search.vector_store import replace_embeddings, delete_photo_embeddings
        params = dict(
            photo_id=self.photo_id, gallery_id=self.gallery_id,
            photographer_id=self.photographer_id, source_version=1,
            model_version="synthetic-integration-test",
        )
        with override_settings(VISUAL_SEARCH_DATABASE_URL=self.url):
            replace_embeddings(**params, vectors=[np.ones(512, dtype=np.float32)])
            self.assertEqual(self._count(), 1)
            replace_embeddings(**params, vectors=[np.zeros(512, dtype=np.float32)])
            self.assertEqual(self._count(), 1)
            delete_photo_embeddings(self.photo_id)
            self.assertEqual(self._count(), 0)

    def test_gallery_purge(self):
        import numpy as np
        from apps.visual_search.vector_store import replace_embeddings, delete_gallery_embeddings
        with override_settings(VISUAL_SEARCH_DATABASE_URL=self.url):
            replace_embeddings(
                photo_id=self.photo_id, gallery_id=self.gallery_id,
                photographer_id=self.photographer_id, source_version=1,
                model_version="synthetic-integration-test",
                vectors=[np.ones(512, dtype=np.float32)],
            )
            self.assertEqual(self._count(), 1)
            delete_gallery_embeddings(self.gallery_id)
            self.assertEqual(self._count(), 0)


class LifecycleIntegrationTests(TestCase):
    """Django transaction hooks without connecting to the external vector DB."""

    def test_photo_deletion_dispatches_purge_after_commit(self):
        from apps.visual_search.signals import photo_deleted
        from apps.galleries.models import GalleryPhoto
        with patch("apps.visual_search.purges.enqueue_purge") as purge:
            with self.captureOnCommitCallbacks(execute=True):
                photo_deleted(sender=GalleryPhoto, instance=GalleryPhoto(pk=991237))
            purge.assert_called_once_with("photo", 991237)

    def test_gallery_deletion_dispatches_purge_after_commit(self):
        from apps.visual_search.signals import gallery_deleted
        from apps.galleries.models import Gallery
        with patch("apps.visual_search.purges.enqueue_purge") as purge:
            with self.captureOnCommitCallbacks(execute=True):
                gallery_deleted(sender=Gallery, instance=Gallery(pk=991238))
            purge.assert_called_once_with("gallery", 991238)

    def test_reconciliation_does_not_touch_vector_db_when_unconfigured(self):
        from apps.visual_search.tasks import reconcile_face_index
        with override_settings(VISUAL_SEARCH_DATABASE_URL=""):
            with patch("apps.visual_search.maintenance.reconcile") as reconcile:
                self.assertEqual(reconcile_face_index.run(), "not_configured")
                reconcile.assert_not_called()
