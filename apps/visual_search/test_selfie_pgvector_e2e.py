"""Optional real pgvector + Django authorization integration tests.

Requires a disposable vector database named lumispixel_visual_search_test*.
The Django test runner must ALSO use an isolated Django test database.
No real images, faces, or customer embeddings are used.
"""
import os
import unittest
from uuid import uuid4

import numpy as np
from django.contrib.auth import get_user_model
from django.test import TestCase, override_settings
from django.utils import timezone

from apps.accounts.models import PhotographerProfile
from apps.billing.models import Plan
from apps.galleries.models import Gallery, GalleryPhoto
from apps.visual_search.models import GalleryFaceSearchPolicy
from apps.visual_search.search import find_public_matches
from apps.visual_search.vector_store import replace_embeddings, delete_photo_embeddings, vector_connection


@unittest.skipUnless(
    os.environ.get("VISUAL_SEARCH_INTEGRATION_DATABASE_URL"),
    "Requires an explicitly configured disposable pgvector database",
)
class RealPgvectorSearchIntegrationTests(TestCase):
    def setUp(self):
        self.vector_url = os.environ["VISUAL_SEARCH_INTEGRATION_DATABASE_URL"]
        with override_settings(VISUAL_SEARCH_DATABASE_URL=self.vector_url):
            with vector_connection() as conn:
                name = conn.execute("SELECT current_database()").fetchone()[0]
                if not name.startswith("lumispixel_visual_search_test"):
                    self.fail("Refusing non-disposable vector database: " + name)
                conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
                conn.execute("CREATE SCHEMA IF NOT EXISTS visual_search")
                conn.execute("""CREATE TABLE IF NOT EXISTS visual_search.app_face_embeddings (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    photo_id bigint NOT NULL, gallery_id bigint NOT NULL,
                    photographer_id bigint NOT NULL, source_version integer NOT NULL,
                    model_version varchar(80) NOT NULL, face_index integer NOT NULL,
                    embedding vector(512) NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
                    UNIQUE (photo_id, source_version, model_version, face_index)
                )""")
        Plan.objects.get_or_create(code="free", defaults={"name": "Free", "is_active": True})
        user = get_user_model().objects.create(email=f"vector-{uuid4().hex}@example.test")
        photographer = PhotographerProfile.objects.create(user=user, slug=f"vector-{uuid4().hex}")
        self.gallery = Gallery.objects.create(
            photographer=photographer, name="Synthetic vector gallery",
            slug=f"vector-{uuid4().hex}", status=Gallery.Status.PUBLISHED,
            visibility=Gallery.Visibility.PUBLIC, published_at=timezone.now(),
        )
        GalleryFaceSearchPolicy.objects.create(
            gallery=self.gallery, processing_authorized=True, global_discovery_enabled=True
        )
        self.photo = GalleryPhoto.objects.create(
            gallery=self.gallery, photographer=photographer, original_name="synthetic.jpg",
            status=GalleryPhoto.Status.COMPLETED, is_visible=True,
        )
        self.vector = np.zeros(512, dtype=np.float32)
        self.vector[0] = 1

    def tearDown(self):
        if hasattr(self, "photo"):
            with override_settings(VISUAL_SEARCH_DATABASE_URL=self.vector_url):
                delete_photo_embeddings(self.photo.pk)

    @override_settings(VISUAL_SEARCH_SELFIE_MAX_DISTANCE=0.4)
    def test_real_vector_match_then_consent_revocation(self):
        with override_settings(
            VISUAL_SEARCH_DATABASE_URL=self.vector_url,
            VISUAL_SEARCH_FACE_MODEL_VERSION="synthetic-integration-test",
        ):
            replace_embeddings(
                photo_id=self.photo.pk, gallery_id=self.gallery.pk,
                photographer_id=self.gallery.photographer_id, source_version=1,
                model_version="synthetic-integration-test", vectors=[self.vector],
            )
            self.assertEqual(
                find_public_matches(self.vector),
                [{"gallery_id": self.gallery.pk}],
            )
            policy = self.gallery.face_search_policy
            policy.processing_authorized = False
            # The vector still exists; authorization must block it immediately.
            from unittest.mock import patch
            with patch("apps.visual_search.purges.dispatch_purge"):
                policy.save()
            self.assertEqual(find_public_matches(self.vector), [])
